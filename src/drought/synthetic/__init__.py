"""Synthetic inputs for every strand of the analysis.

The real inputs — the cantonal parcel data and everything derived from it —
cannot be published. This package generates stand-ins with the same files,
schemas and folder layout, calibrated to the real distributions
(`targets`), so the whole pipeline runs on a fresh clone:

    from drought import synthetic
    synthetic.generate()          # writes data/synthetic/...

Generation is deterministic: one seed (config `synthetic.seed`) is split into
independent streams per product, so changing how one product is drawn does not
reshuffle the others.

Every figure saved while the synthetic profile is active is stamped
"SYNTHETIC DATA" (see `stamp_figures`), so a demo figure cannot be mistaken
for a result.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from . import parcels, series, station, targets

__all__ = ["generate", "parcels", "series", "stamp_figures", "station", "targets"]

STAMP = "SYNTHETIC DATA — demonstrates the method, not the result"


def stamp_figures() -> None:
    """Stamp every figure saved from now on as synthetic.

    Patches `matplotlib.figure.Figure.savefig` once, so it covers every module,
    including figure code that knows nothing about profiles. Idempotent.
    """
    from matplotlib.figure import Figure

    if getattr(Figure.savefig, "_synthetic_stamp", False):
        return
    original = Figure.savefig

    def savefig(self, *args, **kwargs):
        if not getattr(self, "_stamped", False):
            self.text(0.5, 0.5, "SYNTHETIC", fontsize=64, color="#ff3b30", alpha=0.10,
                      ha="center", va="center", rotation=28, fontweight="bold",
                      transform=self.transFigure, zorder=1000)
            self.text(0.995, 0.003, STAMP, fontsize=7, color="#ff3b30", ha="right",
                      va="bottom", fontweight="bold", transform=self.transFigure,
                      zorder=1000,
                      bbox=dict(facecolor="black", edgecolor="none", alpha=0.85, pad=1.5))
            self._stamped = True
        return original(self, *args, **kwargs)

    savefig._synthetic_stamp = True
    Figure.savefig = savefig


def _streams(seed: int) -> dict:
    names = ("parcels", "trajectory", "cuts", "labels", "station")
    kids = np.random.SeedSequence(seed).spawn(len(names))
    return {n: np.random.default_rng(k) for n, k in zip(names, kids)}


def generate(seed: int | None = None, scale: float | None = None,
             verbose: bool = True) -> dict:
    """Write every synthetic input under the synthetic profile's paths.

    Args:
        seed: Master seed (default: config `synthetic.seed`).
        scale: Share of the real parcel count to generate (default: config).
        verbose: Print a summary per product.

    Returns:
        dict of what was written, with the calibration results.
    """
    from .. import config
    from ..config import CFG, gee_dir, labels_path, parcels_dir, station_dir

    config.activate("synthetic")
    seed = CFG.synthetic.seed if seed is None else seed
    scale = CFG.synthetic.scale if scale is None else scale
    rng = _streams(seed)
    root = config.ROOT / "data" / "synthetic"
    root.mkdir(parents=True, exist_ok=True)
    (root / "README.md").write_text(
        "# SYNTHETIC DATA\n\nGenerated by `drought.synthetic.generate()` "
        f"(seed {seed}, scale {scale}). Nothing here is observed data.\n")
    out = {"seed": seed, "scale": scale}

    if verbose:
        print(f"synthetic data, seed {seed}, scale {scale}")
        print("  cadastre: 2017-2025 deliveries")
    pop, dl = parcels.generate(rng["parcels"], scale)
    pdir = parcels_dir()
    for year, gdf in dl.items():
        d = pdir / str(year)
        d.mkdir(parents=True, exist_ok=True)
        gdf.to_file(d / f"nutzungen_{year}.shp")
    truth_cols = ["objectid", "site", "component", "code", "status", "area_ha", "elev_m"]
    pop[truth_cols].to_csv(pdir / "parcels_truth.csv", index=False)
    out["parcels"] = {"n_2025": len(pop), "status": pop.status.value_counts().to_dict(),
                      "by_site": pop.site.value_counts().to_dict()}
    if verbose:
        print(f"    {len(pop):,} parcels in 2025; "
              + ", ".join(f"{k} {v}" for k, v in out["parcels"]["status"].items()))

    # The exports below depend on the mask, as real ones do, so it is built
    # first and every export is registered against it. The build is
    # deterministic: rebuilding gives the same raster, and the records stay valid.
    import contextlib
    import io as _io

    from .. import mask as _mask
    from ..provenance import register
    if verbose:
        print("  building the synthetic mask the exports depend on")
    with contextlib.redirect_stdout(_io.StringIO()):
        _mask.build_mask()

    if verbose:
        print("  site trajectories, calibrated to the real season integrals:")
    traj = series.trajectories(rng["trajectory"], verbose=verbose)
    tpath = config.ROOT / CFG.paths.gee / "grassland_trajectory_multi.csv"
    tpath.parent.mkdir(parents=True, exist_ok=True)
    traj.to_csv(tpath, index=False)
    register(tpath, "trajectory")
    out["trajectory"] = str(tpath.relative_to(config.ROOT))

    if verbose:
        print("  per-parcel cut series and hand labels")
    wide, truth = series.cut_series(rng["cuts"], pop)
    for (site, year), df in wide.items():
        f = gee_dir(site) / f"cuts_{site}_{year}.csv"
        df.to_csv(f, index=False)
        register(f, "cuts")
    labels = series.hand_labels(rng["labels"], truth)
    for site, lab in labels.items():
        with open(labels_path(site), "w") as f:
            json.dump(lab, f, indent=1, sort_keys=True)
    truth.assign(cuts=truth.cuts.map(json.dumps), seen=truth.seen.map(json.dumps)) \
        .to_csv(root / "cuts_truth.csv", index=False)
    out["labels"] = {s: len(v) for s, v in labels.items()}

    if verbose:
        print("  station series")
    st = station.generate(rng["station"])
    for f in station.write(st, station_dir()):
        register(f, "station")
    out["station"] = dict(st.attrs)
    if verbose:
        print(f"  -> {root}")
    return out


def exists() -> bool:
    """Whether a complete synthetic dataset is already on disk."""
    from .. import config

    root = config.ROOT / "data" / "synthetic"
    return (root / "README.md").exists() and (root / "cuts_truth.csv").exists() \
        and any(Path(root, "station").glob("ogd-smn_*_d_*.csv"))
